#!/usr/bin/env python3
"""Generate the backlog views from backlog/stories.toml (single source of truth):
- analysis/10-stories/STORY_<ID>_<short_title>.md   (regenerated when the TOML changes, file name kept; files without the
  generated marker are never overwritten; stories changed after their Analysis are reported)
- reference/backlog/epics/EP-xx.md
- analysis/output/consolidated/backlog_overview.md

Options:
  --deps   print only the compact dependency list (used by the plan step), write nothing
  --csv    also write reference/backlog/tracker-import.csv (generic import for an external tracker)
  --json   print the contract envelope `backlog`: epics and stories (TOML fields + paths of their artifacts), write nothing
  --spec-index  write only delivery/20-specs/README.md (used by the upgrade)
"""
from __future__ import annotations

import csv
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(__file__))
import wf  # noqa: E402


MARKER = "<!-- Generated by tools/gen_backlog.py"
# story sentences in the project language (project.toml language; headings stay English: scripts parse them)
SENTENCES = {
    "en": ("As a {}, I want {}, so that {}.", "Given {}, when {}, then {}."),
    "it": ("Come {}, voglio {}, in modo da {}.", "Dato {}, quando {}, allora {}."),
    "de": ("Als {} möchte ich {}, damit {}.", "Gegeben {}, wenn {}, dann {}."),
    "fr": ("En tant que {}, je veux {}, afin de {}.", "Étant donné {}, quand {}, alors {}."),
    "es": ("Como {}, quiero {}, para {}.", "Dado {}, cuando {}, entonces {}."),
    "pt": ("Como {}, quero {}, para que {}.", "Dado {}, quando {}, então {}."),
}


def sentences() -> tuple[str, str]:
    lang = wf.project().get("project", {}).get("language", "en").split("-")[0]
    return SENTENCES.get(lang, SENTENCES["en"])


def short(s: dict) -> str:
    return s["slug"].replace("-", "_")


def us_md(s: dict, epics: dict) -> str:
    story, given = sentences()
    ac = "\n".join("- " + given.format(g, w, t) for g, w, t in s.get("ac", []))
    req = ", ".join(s.get("fr", []) + s.get("nfr", [])) or "—"
    ep = epics.get(s.get("epic", ""), {})
    return f"""# {s['title']}

## User Story

{story.format(s.get('as_a', '…'), s.get('i_want', '…'), s.get('so_that', '…'))}

## Description

- Epic: {s.get('epic', '—')} — {ep.get('name', '')}
- Priority (MoSCoW): {s.get('priority', '—')} · Release: {s.get('release', '—')} · Size: {s.get('size', '—')} · Type: {s.get('type', '—')}
- Requirements: {req}
- Depends on: {", ".join(s.get('deps', [])) or "—"}
- Notes: {s.get('notes') or "—"}
- Out of scope: {s.get('out_of_scope') or "—"}

## Acceptance Criteria

{ac or "- (none provided)"}

<!-- Generated by tools/gen_backlog.py from backlog/stories.toml: edit the TOML, not this file. -->
"""


SPEC_INDEX = "delivery/20-specs/README.md"


def spec_index() -> str:
    """The Spec index, generated from the Specs (title from the first heading, status, RUN status)."""
    rows = []
    for p in wf.matches("delivery/20-specs/SPEC-*.md"):
        t, name = wf.read(p), os.path.basename(p)
        i = name.split("-")[1]
        title = next((h.lstrip("#") for _, lvl, h in wf.headings(t) if lvl == 1), name).split(" - ", 1)[-1].strip()
        run = wf.one(f"delivery/30-runs/RUN-{i}*.md")
        rows.append(f"| [{i}]({name}) | {title} | {wf.md_status(t) or '—'} | {wf.md_status(wf.read(run)) or '—' if run else '—'} |")
    return ("# Spec index\n\nGenerated by `make backlog` from the Specs (`delivery/AGENT_GUIDE.md` §6). Do not edit by hand.\n\n"
            "| ID | Title | Status | RUN |\n|----|------|--------|-----|\n" + "".join(r + "\n" for r in rows))


def main() -> None:
    if "--spec-index" in sys.argv:  # only the Spec index (used by the upgrade, which never touches Story files)
        if wf.matches("delivery/20-specs/SPEC-*.md") and (not wf.exists(SPEC_INDEX) or wf.read(SPEC_INDEX) != spec_index()):
            wf.write(SPEC_INDEX, spec_index())
            print(f"regenerated {SPEC_INDEX}")
        return
    if "--json" in sys.argv:
        try:
            b = wf.backlog()
            if errs := wf.backlog_errors():
                raise ValueError("; ".join(errs))
        except (OSError, ValueError) as e:  # tomllib.TOMLDecodeError is a ValueError
            wf.fail_envelope("backlog", "bad_input", str(e))
        wf.dump_envelope("backlog", {"status": b.get("status"), "epics": list({e["id"]: e for e in b.get("epic", [])}.values()),
                                     "stories": [{**s, "artifacts": wf.artifacts(s["id"])} for s in b.get("story", [])]})
        return
    b = wf.backlog()
    if errs := wf.backlog_errors():
        sys.exit("\n".join(errs) + "\nfix backlog/stories.toml, then rerun")
    stories = b.get("story", [])
    epics = {e["id"]: e for e in b.get("epic", [])}
    if "--deps" in sys.argv:
        for s in stories:
            print(f"{s['id']} [{s.get('epic', '')} {s.get('priority', '')} {s.get('size', '')} {s.get('release', '')}] "
                  f"{s['title']} ← {', '.join(s.get('deps', [])) or '—'}")
        return
    if wf.matches("delivery/20-specs/SPEC-*.md") and (not wf.exists(SPEC_INDEX) or wf.read(SPEC_INDEX) != spec_index()):
        wf.write(SPEC_INDEX, spec_index())
    if not stories:
        print("backlog/stories.toml has no stories: nothing to generate")
        return

    written = unchanged = 0
    kept: list[str] = []
    drifted: list[str] = []
    for s in stories:
        cur = wf.one(f"analysis/10-stories/STORY_{s['id']}_*.md")
        text = us_md(s, epics)
        if cur:
            old = wf.read(cur)
            if MARKER not in old:
                kept.append(s["id"])
                continue
            if old == text:
                unchanged += 1
                continue
            if wf.matches(f"analysis/20-analysis/ANALYSIS_{s['id']}_*.md"):
                drifted.append(s["id"])
        wf.write(cur or f"analysis/10-stories/STORY_{s['id']}_{short(s)}.md", text)
        written += 1

    for k, e in epics.items():
        rows = [s for s in stories if s.get("epic") == k]
        wf.write(f"reference/backlog/epics/{k}.md",
                 f"# {k} — {e.get('name', '')}\n\n{e.get('description', '')}\n\n"
                 "| Story | Title | Priority | Release | Size | Depends on |\n|---|---|---|---|---|---|\n"
                 + "\n".join(f"| [{s['id']}](../../../analysis/10-stories/STORY_{s['id']}_{short(s)}.md) | {s['title']} | {s.get('priority', '')} | "
                             f"{s.get('release', '')} | {s.get('size', '')} | {', '.join(s.get('deps', [])) or '—'} |" for s in rows) + "\n")

    name = wf.project().get("project", {}).get("name", "")
    c = Counter(s.get("priority", "?") for s in stories)
    ov = [f"# Backlog overview — {name}", "",
          "Generated by `tools/gen_backlog.py` from `backlog/stories.toml`. Do not edit by hand.", "",
          "| ID | Title | Epic | Priority | Release | Size | Deps | Analysis | Refined Story |", "|---|---|---|---|---|---|---|---|---|"]
    for s in stories:
        analysis = "✓" if wf.matches(f"analysis/20-analysis/ANALYSIS_{s['id']}_*.md") else "—"
        refine = "✓" if wf.matches(f"analysis/30-refined/REFINED_{s['id']}_*.md") else "—"
        ov.append(f"| {s['id']} | {s['title']} | {s.get('epic', '')} | {s.get('priority', '')} | {s.get('release', '')} | "
                  f"{s.get('size', '')} | {', '.join(s.get('deps', [])) or '—'} | {analysis} | {refine} |")
    ov += ["", f"Total: {len(stories)} · " + " · ".join(f"{k}: {v}" for k, v in sorted(c.items()))]
    wf.write("analysis/output/consolidated/backlog_overview.md", "\n".join(ov) + "\n")

    if "--csv" in sys.argv:
        os.makedirs(wf.path("reference/backlog"), exist_ok=True)
        with open(wf.path("reference/backlog/tracker-import.csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["Type", "ID", "Title", "Description", "Acceptance Criteria", "Priority", "Size", "Release", "Parent"])
            for k, e in epics.items():
                w.writerow(["Epic", k, e.get("name", ""), e.get("description", ""), "", "", "", "", ""])
            story, given = sentences()
            for s in stories:
                w.writerow(["User Story", s["id"], s["title"], story.format(s.get("as_a"), s.get("i_want"), s.get("so_that")),
                            "\n".join(given.format(g, wh, t) for g, wh, t in s.get("ac", [])),
                            s.get("priority", ""), s.get("size", ""), s.get("release", ""), s.get("epic", "")])
    print(f"Story written {written}, unchanged {unchanged}, total {len(stories)}"
          + (f" · hand-written, not overwritten: {', '.join(kept)}" if kept else ""))
    if drifted:
        print(f"Changed after Analysis (align Analysis/Refined Story): {', '.join(drifted)}")


if __name__ == "__main__":
    main()
