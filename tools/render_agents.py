#!/usr/bin/env python3
"""Render the tool adapters from the neutral workflow source.

Sources: workflow/workflow.toml (steps, commands, agents) + models.toml (tier → model per tool).
Outputs, for each tool enabled in models.toml:
  claude-code  CLAUDE.md, .claude/commands/*.md, .claude/agents/*.md, .claude/settings.json
  codex        .codex/prompts/*.md            (AGENTS.md is read natively)
  copilot      .github/prompts/*.prompt.md, .github/copilot-instructions.md
  cursor       .cursor/commands/*.md, .cursor/rules/workflow.mdc
and always workflow/STEPS.md (the step / command / tier table).

Files a project already owns (an existing CLAUDE.md, .github/copilot-instructions.md, .claude/settings.json, e.g. after
tools/adopt.py) are merged, not overwritten: markdown gets a marked block, settings.json the union of the permissions.

Usage:
  python3 tools/render_agents.py           # write
  python3 tools/render_agents.py --check   # exit 1 if any generated file is stale (used by make check)
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import wf  # noqa: E402

MANIFEST = "workflow/.generated"
HDR = "Generated by tools/render_agents.py from workflow/workflow.toml and models.toml — do not edit; run `make agents`."
BEGIN, END = "<!-- agentic-workflow:begin -->", "<!-- agentic-workflow:end -->"
ARGS = {"claude-code": "$ARGUMENTS", "codex": "$ARGUMENTS", "copilot": "${input:args}", "cursor": "<the text typed after the command>"}


def body(cmd: dict, tool: str) -> str:
    return cmd["body"].strip().replace("$ARGUMENTS", ARGS[tool]) + "\n"


def model_note(tool: str, tier: str) -> str:
    return f"> Recommended model: **{wf.model_for(tool, tier)}** (tier `{tier}`, see models.toml). Switch to it before running this command.\n\n"


def yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def put_block(text: str, body: str) -> str:
    block = f"{BEGIN}\n<!-- {HDR} -->\n{body.strip()}\n{END}"
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    return text.rstrip() + "\n\n" + block + "\n"


def merge(p: str, generated: str, block: str | None) -> str:
    """What to write at p: the generated file, or the project's own file with our part merged in."""
    if not wf.exists(p):
        return generated
    cur = wf.read(p)
    if p.endswith("settings.json"):
        try:
            data = json.loads(cur)
        except ValueError:
            sys.exit(f"{p}: invalid JSON; fix it, then run `make agents`")
        perms = data.setdefault("permissions", {})
        for k, v in json.loads(generated)["permissions"].items():
            perms[k] = perms.get(k, []) + [x for x in v if x not in perms.get(k, [])]
        return json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if block is not None and (BEGIN in cur or not cur.startswith("<!-- Generated")):
        return put_block(cur, block)
    return generated


def retire(p: str) -> str | None:
    """Content of a previously generated file once our part is removed; None = delete the file."""
    cur = wf.read(p)
    if BEGIN in cur and END in cur:
        rest = (cur[:cur.index(BEGIN)].rstrip() + "\n" + cur[cur.index(END) + len(END):].lstrip("\n")).strip()
        return rest + "\n" if rest else None
    if p.endswith("settings.json"):
        try:
            data = json.loads(cur)
        except ValueError:
            return None
        perms = data.get("permissions", {})
        for k, v in SETTINGS["permissions"].items():
            perms[k] = [x for x in perms.get(k, []) if x not in v]
            if not perms[k]:
                del perms[k]
        if not perms:
            data.pop("permissions", None)
        return json.dumps(data, indent=2, ensure_ascii=False) + "\n" if data else None
    return None


SETTINGS = {
    "permissions": {
        "allow": ["Bash(make next)", "Bash(make check)", "Bash(make backlog)", "Bash(make agents)", "Bash(make test-tools)",
                  "Bash(python3 tools/next_step.py:*)", "Bash(python3 tools/context.py:*)", "Bash(python3 tools/gen_backlog.py:*)",
                  "Bash(python3 tools/check_workflow.py)", "Bash(git status)", "Bash(git diff:*)", "Bash(git log:*)"],
        "deny": ["Bash(git push --force:*)", "Bash(terraform apply:*)", "Read(./.env)", "Read(./.env.*)"],
    }
}


def render() -> dict[str, str]:
    w = wf.workflow()
    cmds = w.get("commands", {})
    agents = w.get("agents", {})
    tools = wf.enabled_tools()
    out: dict[str, str] = {}
    blocks: dict[str, str] = {}  # body merged into a file the project already owns

    if "claude-code" in tools:
        claude = ("@AGENTS.md\n\n"
                  "Claude Code specifics:\n"
                  "- Start with `/next`; between steps use `/clear` (except the `/run` chain of the same story).\n"
                  "- Each command pins its model in the frontmatter (tier → model in `models.toml`). Do not switch to a larger model unless the user asks.\n"
                  "- Subagents in `.claude/agents/` only for independent workstreams.\n")
        out["CLAUDE.md"] = f"<!-- {HDR} -->\n# CLAUDE.md\n\n{claude}"
        blocks["CLAUDE.md"] = "## Agentic workflow\n\n" + claude
        for name, c in cmds.items():
            fm = [f"description: {yaml_str(c['description'])}"]
            if c.get("args"):
                fm.append(f"argument-hint: {yaml_str(c['args'])}")
            fm.append(f"model: {wf.model_for('claude-code', c['tier'])}")
            if c.get("tools"):
                fm.append(f"allowed-tools: {', '.join(c['tools'])}")
            out[f".claude/commands/{name}.md"] = "---\n" + "\n".join(fm) + "\n---\n" + f"<!-- {HDR} -->\n" + body(c, "claude-code")
        for name, a in agents.items():
            out[f".claude/agents/{name}.md"] = ("---\n" f"name: {name}\n" f"description: {yaml_str(a['description'])}\n"
                                                f"model: {wf.model_for('claude-code', a['tier'])}\n" f"tools: {', '.join(a.get('tools', []))}\n"
                                                "---\n" f"<!-- {HDR} -->\n" + a["body"].strip() + "\n")
        out[".claude/settings.json"] = json.dumps(SETTINGS, indent=2) + "\n"

    if "codex" in tools:
        for name, c in cmds.items():
            fm = f"---\ndescription: {yaml_str(c['description'])}\n" + (f"argument-hint: {yaml_str(c['args'])}\n" if c.get("args") else "") + "---\n"
            out[f".codex/prompts/{name}.md"] = fm + f"<!-- {HDR} -->\n" + model_note("codex", c["tier"]) + body(c, "codex")

    if "copilot" in tools:
        copilot = "Follow `AGENTS.md` at the repository root: it is the canonical rule set. Start with the `/next` prompt; one workflow step per chat.\n"
        out[".github/copilot-instructions.md"] = f"<!-- {HDR} -->\n# Copilot instructions\n\n{copilot}"
        blocks[".github/copilot-instructions.md"] = "## Agentic workflow\n\n" + copilot
        for name, c in cmds.items():
            fm = ["mode: 'agent'", f"description: {yaml_str(c['description'])}", f"model: {yaml_str(wf.model_for('copilot', c['tier']))}"]
            out[f".github/prompts/{name}.prompt.md"] = "---\n" + "\n".join(fm) + "\n---\n" + f"<!-- {HDR} -->\n" + \
                (f"Arguments ({c['args']}): ${{input:args}}\n\n" if c.get("args") else "") + body(c, "copilot").replace("${input:args}", "the arguments above")

    if "cursor" in tools:
        out[".cursor/rules/workflow.mdc"] = ("---\ndescription: Agentic workflow rules\nalwaysApply: true\n---\n"
                                             f"<!-- {HDR} -->\nFollow `AGENTS.md` at the repository root (canonical rules). Start with the `/next` command; one workflow step per chat.\n")
        for name, c in cmds.items():
            out[f".cursor/commands/{name}.md"] = f"<!-- {HDR} -->\n# /{name}\n\n{c['description']}\n\n" + \
                (f"Arguments: {c['args']}\n\n" if c.get("args") else "") + model_note("cursor", c["tier"]) + body(c, "cursor")

    # step table (documentation, always)
    rows = ["| Step | Owner | Mode | Command | Tier | " + " | ".join(tools) + " | Session |", "|---|---|---|---|---|" + "---|" * len(tools) + "---|"]
    for sid, s in w.get("steps", {}).items():
        tier = s.get("tier", "")
        rows.append(f"| [`{sid}`](steps/{sid}.md) | {s.get('owner', '')} | {s.get('mode', '')} | {('/' + s['command']) if s.get('command') else '—'} | "
                    f"{tier or '—'} | " + " | ".join(wf.model_for(t, tier) if tier else "—" for t in tools) + f" | {s.get('session', '—')} |")
    out["workflow/STEPS.md"] = (f"<!-- {HDR} -->\n# Workflow steps\n\nOrder: inception (kickoff → requirements → mockup → architecture → backlog → plan; "
                                "existing codebase: tools/adopt.py → onboard → backlog → plan), then per story analysis → workshop → refine → brief-spec → spec-approval → run-strategy → run-approval → execute → tuning → review.\n\n"
                                + "\n".join(rows) + "\n\nCommands: " + ", ".join(f"`/{c}`" for c in cmds) + ".\n")
    return {p: merge(p, t, blocks.get(p)) for p, t in out.items()}


def previous() -> list[str]:
    return [line for line in wf.read(MANIFEST).splitlines() if line] if wf.exists(MANIFEST) else []


def check(files: dict[str, str]) -> list[str]:
    stale = [p for p, t in files.items() if not wf.exists(p) or wf.read(p) != t]
    stale += [p for p in previous() if p not in files and wf.exists(p) and retire(p) != wf.read(p)]
    return stale


def main() -> None:
    files = render()
    if "--check" in sys.argv:
        stale = check(files)
        for p in stale:
            print(f"stale: {p}")
        print("adapters up to date" if not stale else f"{len(stale)} stale adapter files: run `make agents`")
        sys.exit(1 if stale else 0)
    for p in previous():
        if p not in files and wf.exists(p):
            rest = retire(p)
            if rest is None:
                os.remove(wf.path(p))
            elif rest != wf.read(p):
                wf.write(p, rest)
    for p, t in files.items():
        wf.write(p, t)
    wf.write(MANIFEST, "\n".join(sorted(files)) + "\n")
    print(f"rendered {len(files)} files for: {', '.join(wf.enabled_tools()) or 'no tool'}")


if __name__ == "__main__":
    main()
